BEGIN;


CREATE TABLE teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Original ID from the legacy CFBR Database, DELETE later
    legacy_team_id INTEGER UNIQUE,

    name CITEXT NOT NULL UNIQUE,

    primary_color TEXT NOT NULL,
    secondary_color TEXT NOT NULL,

    logo TEXT NOT NULL,

    seasons INTEGER[] NOT NULL DEFAULT '{}',

    CONSTRAINT teams_name_not_blank
        CHECK (length(trim(name::TEXT)) > 0),

    CONSTRAINT teams_primary_color_valid
        CHECK (primary_color ~ '^#[0-9A-Fa-f]{6}$'),

    CONSTRAINT teams_secondary_color_valid
        CHECK (secondary_color ~ '^#[0-9A-Fa-f]{6}$'),

    CONSTRAINT teams_logo_not_blank
        CHECK (length(trim(logo)) > 0)
);

COMMIT;