
BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Authentication principal issued by Keycloak.
    -- Nullable during staged migration / account provisioning.
    keycloak_subject TEXT UNIQUE,

    display_name TEXT,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    -- Retained when accounts are merged; do not delete the source user.
    merged_into_user_id BIGINT
        REFERENCES users(id) ON DELETE RESTRICT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT users_no_self_merge
        CHECK (merged_into_user_id IS NULL OR merged_into_user_id <> id)
);

CREATE INDEX IF NOT EXISTS ix_users_merged_into_user_id
    ON users (merged_into_user_id);


-- External provider identities linked to a CFBR user.
-- Provider subjects must come from trusted OAuth/OIDC identity data,
-- never from usernames or display names.
CREATE TABLE IF NOT EXISTS user_auth (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    provider TEXT NOT NULL,
    provider_subject TEXT NOT NULL,
    provider_username TEXT,

    linked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT user_auth_provider_check
        CHECK (provider IN ('reddit', 'discord')),

    CONSTRAINT user_auth_provider_subject_unique
        UNIQUE (provider, provider_subject),

    CONSTRAINT user_auth_user_provider_unique
        UNIQUE (user_id, provider)
);

CREATE INDEX IF NOT EXISTS ix_user_auth_user_id
    ON user_auth (user_id);


-- Maps IDs from the legacy Risk database to CFBR application users.
-- Keep legacy IDs as migration references; do not reuse them as CFBR IDs.
CREATE TABLE IF NOT EXISTS legacy_user_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_system TEXT NOT NULL DEFAULT 'risk',
    legacy_user_id INTEGER NOT NULL,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    migrated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT legacy_user_mapping_source_id_unique
        UNIQUE (source_system, legacy_user_id),

    CONSTRAINT legacy_user_mapping_user_unique
        UNIQUE (source_system, user_id)
);

CREATE INDEX IF NOT EXISTS ix_legacy_user_mappings_user_id
    ON legacy_user_mappings (user_id);


-- Audit trail for explicit account merges.
-- Both user rows remain available for history and audit purposes.
CREATE TABLE IF NOT EXISTS user_merge_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,
    target_user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,
    actor_user_id BIGINT
        REFERENCES users(id) ON DELETE RESTRICT,

    merged_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,

    CONSTRAINT user_merge_events_no_self_merge
        CHECK (source_user_id <> target_user_id)
);

CREATE INDEX IF NOT EXISTS ix_user_merge_events_source_user_id
    ON user_merge_events (source_user_id);

CREATE INDEX IF NOT EXISTS ix_user_merge_events_target_user_id
    ON user_merge_events (target_user_id);

    
CREATE TABLE IF NOT EXISTS player_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,
-- TODO: Add foreign key once games has been created
    game_id BIGINT NOT NULL,
    current_team_id BIGINT NOT NULL
        REFERENCES teams(id) ON DELETE RESTRICT,
    playing_for_team_id BIGINT NOT NULL
        REFERENCES teams(id) ON DELETE RESTRICT,

    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT player_memberships_user_game_unique
        UNIQUE (user_id, game_id)
);


COMMIT;
